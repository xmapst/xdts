// 不验签、不查 Node.TokenHash：节点发第一条 register.request 时既
// 没有 x-node-id（自己还不知道分配到的 ID），Manager 这边也没有对应的
// Node 行可查——注册流程本身就是"从零信任建立起第一份共享凭据"的过程，
// 此时使用 register_code 校验注册资格，回复依赖本中心 Broker 的传输安全。
func (d *Dispatcher) onRegisterReq(ctx context.Context, env *iproto.Envelope) error {
	ctx, cancel := context.WithTimeout(ctx, 20*time.Second)
	defer cancel()
	var req iproto.RegisterRequest
	if err := iproto.Decode(env.Body, env.Properties.ContentEncoding, &req); err != nil {
		return fmt.Errorf("dispatch: 解码 register.request 失败: %w", err)
	}

	pub := d.publisher()
	if pub == nil {
		return fmt.Errorf("dispatch: amqp publisher not wired yet, cannot reply to register.request")
	}
	replyKey, ok := transport.ReplyRoutingKeyFor(env)
	if !ok {
		return fmt.Errorf("dispatch: register.request 缺少 %s header，无法回复", iproto.HeaderReplyKey)
	}

	reply := d.registerNode(ctx, &req)
	body, encoding, err := iproto.Encode(reply, iproto.EncodeOptions{Compress: false})
	if err != nil {
		return fmt.Errorf("dispatch: 编码 register.reply 失败: %w", err)
	}
	replyEnv := iproto.NewEnvelope(body, iproto.NewEnvelopeParams{
		// Direct publication requires an explicit message ID; RPC defaults do not apply.
		MessageID:       uuidx.New().String(),
		CorrelationID:   env.Properties.CorrelationID,
		Type:            iproto.MessageTypeRegisterReply,
		TimestampMS:     d.now().UnixMilli(),
		ProtocolVersion: iproto.CurrentProtocolVersion(),
		ContentEncoding: encoding,
	})

	outcome, err := pub.PublishEnvelope(ctx, transport.ExchangeReply, replyKey, replyEnv)
	if err != nil {
		return fmt.Errorf("dispatch: 发布 register.reply 失败: %w", err)
	}
	if outcome != transport.OutcomeConfirmed {
		return fmt.Errorf("dispatch: register.reply 未被判定为已投递，outcome=%s", outcome)
	}
	return nil
}

// 注册失败（码无效/过期/已用）是节点必须知道的业务结果，不是 Manager 的
// 内部错误：节点据此决定"换一个码"还是"联系管理员"。若返回 error 让上层只记
// 日志不回复，节点会一直等到超时——那正是本文件顶部文档要避免的"占位分支静默
// 丢弃"的等价后果（丢弃位置从"没人处理"变成"处理了但不回信"）。
func (d *Dispatcher) registerNode(ctx context.Context, req *iproto.RegisterRequest) *iproto.RegisterReply {
	// Registration is idempotent by the instance ID generated by Node.
	if d.db == nil {
		slog.ErrorContext(ctx, "register request rejected: manager db not wired",
			slog.String("hostname", req.GetHostname()))
		return &iproto.RegisterReply{
			Error:           &iproto.Error{Code: "SERVICE_UNAVAILABLE", Message: "Manager 尚未就绪，请稍后重试"},
			ProtocolVersion: iproto.CurrentProtocolVersion(),
		}
	}
	if req.GetProtocolVersion() != iproto.CurrentProtocolVersion() {
		return &iproto.RegisterReply{Error: &iproto.Error{Code: "PROTOCOL_INCOMPATIBLE", Message: "协议版本不匹配，请使用相同版本的节点和 Manager"}, ProtocolVersion: iproto.CurrentProtocolVersion()}
	}
	if req.GetInstanceId() == "" {
		return &iproto.RegisterReply{Error: &iproto.Error{Code: "INVALID_INSTANCE_ID", Message: "注册请求缺少 instance_id"}, ProtocolVersion: iproto.CurrentProtocolVersion()}
	}
	result, err := repo.NewNodeRegistrations(d.db).Register(ctx, req.GetInstanceId(), repo.RegisterNodeParams{
		PlainRegisterCode: req.GetRegisterCode(), Hostname: req.GetHostname(), IPs: strings.Join(req.GetIps(), ","),
		OSArch: req.GetOsArch(), Version: req.GetNodeVersion(),
	}, d.now())
	if err != nil {
		return registerFailureReply(ctx, req, err)
	}
	slog.InfoContext(ctx, "node registration resolved", slog.String("node_id", result.NodeID.String()), slog.String("center_code", result.CenterCode))

	return &iproto.RegisterReply{
		NodeId:          result.NodeID.String(),
		NodeToken:       result.Token,
		CenterCode:      result.CenterCode,
		ProtocolVersion: iproto.CurrentProtocolVersion(),
	}
}

// registerFailureReply 把 repo 的哨兵错误映射成节点可判别的错误码。
//
// **不透传 err 的文字**给节点：repo 的错误消息是给我们自己排障的，不是对节点
// 的契约（同一条理由见 internal/manager/http/events.go 里"不靠匹配 repo 中文错误子串来分流"）。
func registerFailureReply(ctx context.Context, req *iproto.RegisterRequest, err error) *iproto.RegisterReply {
	code, msg := "INTERNAL", "注册处理失败，请联系管理员"
	switch {
	case errors.Is(err, repo.ErrRegistrationInstanceInvalid):
		code, msg = "INVALID_INSTANCE_ID", "注册实例标识必须是非空规范 UUID"
	case errors.Is(err, repo.ErrRegistrationInstanceConflict):
		code, msg = "REGISTRATION_INSTANCE_CONFLICT", "该注册实例已绑定其他注册码，请使用新的注册实例"
	case errors.Is(err, repo.ErrNodeNameConflict):
		code, msg = "NODE_NAME_CONFLICT", "节点名称已存在，请修改注册预设名称后重试"
	case errors.Is(err, repo.ErrResourceNameInvalid):
		code, msg = "INVALID_REGISTRATION_METADATA", "节点名称不能为空，且不能超过 128 个字符"
	case errors.Is(err, repo.ErrRegistrationMetadataInvalid):
		code, msg = "INVALID_REGISTRATION_METADATA", "节点名称或主机信息超过允许范围"
	case errors.Is(err, repo.ErrNodeIdentityRetired):
		code, msg = "NODE_IDENTITY_RETIRED", "节点身份已吊销或注销，请使用新注册码和新数据目录重新注册"
	case errors.Is(err, repo.ErrCenterNotFound):
		code, msg = "REGISTER_CENTER_NOT_FOUND", "注册码绑定的中心已不存在，请向管理员索取新的注册码"
	case errors.Is(err, repo.ErrRegisterCodeNotFound):
		code, msg = "REGISTER_CODE_NOT_FOUND", "注册码不存在，请确认后重新输入"
	case errors.Is(err, repo.ErrRegisterCodeRevoked):
		code, msg = "REGISTER_CODE_REVOKED", "注册码已被作废，请向管理员索取新的注册码"
	case errors.Is(err, repo.ErrRegisterCodeExpired):
		code, msg = "REGISTER_CODE_EXPIRED", "注册码已过期，请向管理员索取新的注册码"
	case errors.Is(err, repo.ErrRegisterCodeExhausted):
		// **不写"请稍后重试"**（原占位文案就是这么写的）：一码一节点、
		// max_uses=1，这一档重试必然再次失败。一句让人去做必然失败的事的提示，
		// 比没有提示更坏——它把"换一个码"这个唯一出路藏起来了。
		//
		// 已完成的同实例重试在仓储中先返回原身份；此处只拒绝另一实例。
		code, msg = "REGISTER_CODE_EXHAUSTED", "注册码已被使用（一码一节点），请向管理员索取新的注册码"
	default:
		// 只有非预期错误才记 Error：四个哨兵是正常业务结果，记 Error 会让
		// "有人输错注册码"和"数据库故障"在日志级别上不可分。
		slog.ErrorContext(ctx, "node registration failed",
			slog.String("hostname", req.GetHostname()),
			slog.Any("error", err))
	}
	return &iproto.RegisterReply{
		Error:           &iproto.Error{Code: code, Message: msg},
		ProtocolVersion: iproto.CurrentProtocolVersion(),
	}
}
